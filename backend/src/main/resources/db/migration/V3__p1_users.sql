-- Phase 1: user accounts, external auth providers, one-time tokens, login throttling.

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email               CITEXT       NOT NULL,
    display_name        VARCHAR(100) NOT NULL,
    password_hash       VARCHAR(255),
    locale              VARCHAR(2)   NOT NULL DEFAULT 'pl',
    email_verified_at   TIMESTAMPTZ,
    privacy_accepted_at TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_locale CHECK (locale IN ('pl', 'en')),
    CONSTRAINT ck_users_display_name CHECK (length(btrim(display_name)) > 0)
);

-- Login methods other than the password (D-5, D-38). Google only in MVP.
CREATE TABLE user_auth_providers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT       NOT NULL,
    provider   VARCHAR(20)  NOT NULL,
    subject    VARCHAR(255) NOT NULL,
    email      CITEXT,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_auth_providers PRIMARY KEY (id),
    CONSTRAINT fk_user_auth_providers_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_user_auth_providers_subject UNIQUE (provider, subject),
    CONSTRAINT uk_user_auth_providers_user_provider UNIQUE (user_id, provider),
    CONSTRAINT ck_user_auth_providers_provider CHECK (provider IN ('GOOGLE'))
);
CREATE INDEX ix_user_auth_providers_user ON user_auth_providers (user_id);

-- One-time tokens are stored only as SHA-256 hashes (D-12).
CREATE TABLE email_verification_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT      NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_email_verification_tokens PRIMARY KEY (id),
    CONSTRAINT fk_email_verification_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_email_verification_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX ix_email_verification_tokens_user ON email_verification_tokens (user_id);

CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT      NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_password_reset_tokens PRIMARY KEY (id),
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_password_reset_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX ix_password_reset_tokens_user ON password_reset_tokens (user_id);

-- Per-email rate limiting that survives restarts (D-10). One row per (action, email) and time window.
CREATE TABLE email_rate_limits (
    action       VARCHAR(40) NOT NULL,
    email        CITEXT      NOT NULL,
    window_start TIMESTAMPTZ NOT NULL,
    attempts     INT         NOT NULL DEFAULT 0,
    CONSTRAINT pk_email_rate_limits PRIMARY KEY (action, email)
);
