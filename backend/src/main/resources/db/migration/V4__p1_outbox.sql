-- Phase 1: transactional outbox for notifications (CLAUDE.md §3).
-- Events are written in the same transaction as the business change; a scheduled dispatcher delivers them.

CREATE TABLE outbox_events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    type              VARCHAR(64)  NOT NULL,
    recipient_user_id BIGINT,
    recipient_email   CITEXT,
    recipient_locale  VARCHAR(2),
    payload           JSONB        NOT NULL DEFAULT '{}'::jsonb,
    dedup_key         VARCHAR(200),
    status            VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    attempts          INT          NOT NULL DEFAULT 0,
    next_attempt_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_error        VARCHAR(1000),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    processed_at      TIMESTAMPTZ,
    CONSTRAINT pk_outbox_events PRIMARY KEY (id),
    CONSTRAINT fk_outbox_events_recipient_user FOREIGN KEY (recipient_user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_outbox_events_dedup_key UNIQUE (dedup_key),
    CONSTRAINT ck_outbox_events_status CHECK (status IN ('PENDING', 'DONE', 'FAILED')),
    CONSTRAINT ck_outbox_events_recipient CHECK (
        (recipient_user_id IS NOT NULL AND recipient_email IS NULL)
        OR (recipient_user_id IS NULL AND recipient_email IS NOT NULL AND recipient_locale IN ('pl', 'en'))
    )
);
CREATE INDEX ix_outbox_events_due ON outbox_events (next_attempt_at) WHERE status = 'PENDING';
CREATE INDEX ix_outbox_events_recipient_user ON outbox_events (recipient_user_id);

-- One row per successfully delivered (event, channel): makes retries idempotent per channel.
CREATE TABLE notification_deliveries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    outbox_event_id BIGINT      NOT NULL,
    channel         VARCHAR(16) NOT NULL,
    delivered_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_notification_deliveries PRIMARY KEY (id),
    CONSTRAINT fk_notification_deliveries_event FOREIGN KEY (outbox_event_id) REFERENCES outbox_events (id) ON DELETE CASCADE,
    CONSTRAINT uk_notification_deliveries_event_channel UNIQUE (outbox_event_id, channel),
    CONSTRAINT ck_notification_deliveries_channel CHECK (channel IN ('EMAIL', 'IN_APP', 'PUSH'))
);
